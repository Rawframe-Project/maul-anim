// Writes the meshopt decoder's test streams
// (test/gltf_meshopt_fixtures.h in maul-anim) with meshoptimizer's
// encoders (zeux, MIT, commit f0a684f1), so the library's tests need no
// meshoptimizer. Each stream keeps the data it encodes; each filter case
// keeps its encoded input and meshoptimizer's decoded output (the
// specification allows one unit between decoders). The version 1
// attribute stream's data is built so its first block uses every control
// mode (bit-length sets 0 and 1, zeros, literal) and channel modes 0, 1
// and 2; the tool checks that it does. Triangle streams keep
// meshoptimizer's decoding, since its encoder may rotate a triangle.
//
// usage: meshopt_fixtures > gltf_meshopt_fixtures.h, then clang-format -i it
// Build: g++-14 -O2 -std=c++17 -I<meshoptimizer>/src meshopt_fixtures.cc
// libmeshoptimizer.a. Not library code.
#include "meshoptimizer.h"

#include <cmath>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <string>
#include <vector>

static uint64_t s_state = 0x2545F4914F6CDD1Dull;

static uint32_t Next()
{
    s_state ^= s_state << 13;
    s_state ^= s_state >> 7;
    s_state ^= s_state << 17;
    return (uint32_t)(s_state >> 16);
}

static void Bytes(const char* name, const unsigned char* p, size_t n)
{
    printf("static const uint8_t %s[%zu] = {", name, n > 0 ? n : 1);
    for (size_t i = 0; i < n; ++i)
    {
        printf("%s0x%02x", i % 16 == 0 ? "\n    " : " ", p[i]);
        printf(i + 1 < n ? "," : "");
    }
    printf(n == 0 ? "0};\n" : "};\n");
}

struct Case
{
    std::string name;
    size_t size;
    size_t count;
    size_t stride;
    int mode;
    bool v1;
};

static std::vector<Case> s_cases;

static void Stream(const char* name, const std::vector<unsigned char>& stream,
                   const std::vector<unsigned char>& data, size_t count, size_t stride, int mode,
                   bool v1)
{
    std::string s = std::string("k") + name;
    Bytes(s.c_str(), stream.data(), stream.size());
    Bytes((s + "Out").c_str(), data.data(), count * stride);
    s_cases.push_back({name, stream.size(), count, stride, mode, v1});
}

static std::vector<unsigned char> Attributes(const std::vector<unsigned char>& data, size_t count,
                                             size_t stride, int level, int version)
{
    std::vector<unsigned char> s(meshopt_encodeVertexBufferBound(count, stride));
    s.resize(meshopt_encodeVertexBufferLevel(s.data(), s.size(), data.data(), count, stride, level,
                                             version));
    return s;
}

int main()
{
    printf("// SPDX-License-Identifier: MIT\n// Copyright (c) 2026 Sirac Ozmen\n//\n"
           "// Generated by tools/meshopt_fixtures.cc with\n"
           "// meshoptimizer's encoders, commit f0a684f1 (MIT): streams with the data\n"
           "// they encode, and filter inputs with meshoptimizer's decoded output.\n"
           "// Do not edit.\n\n"
           "#ifndef MAUL_ANIM_TEST_GLTF_MESHOPT_FIXTURES_H\n"
           "#define MAUL_ANIM_TEST_GLTF_MESHOPT_FIXTURES_H\n\n#include <stdint.h>\n\n");
    // Version 0: 37 elements of 8 bytes, smooth.
    {
        size_t count = 37, stride = 8;
        std::vector<unsigned char> d(count * stride);
        for (size_t i = 0; i < count; ++i)
        {
            for (size_t k = 0; k < stride; ++k)
            {
                d[i * stride + k] = (unsigned char)(i * (k + 1) + (Next() % 3));
            }
        }
        Stream("AttributesV0", Attributes(d, count, stride, 2, 0), d, count, stride, 0, false);
    }
    // Version 1 over two blocks (257 elements of 12 bytes; blocks of 256):
    // bytes 0-3 counting, in steps (whole groups of zero deltas), zero and
    // noise (every control mode); 4-7 two 16-bit smooth values (2-byte
    // deltas); 8-11 a float changing sign each element (XOR deltas).
    {
        size_t count = 257, stride = 12;
        std::vector<unsigned char> d(count * stride);
        float f = 1.75f;
        for (size_t i = 0; i < count; ++i)
        {
            unsigned char* e = &d[i * stride];
            e[0] = (unsigned char)i;
            e[1] = (unsigned char)((i / 40) % 3);
            e[2] = 0;
            e[3] = (unsigned char)Next();
            uint16_t a = (uint16_t)(1000 + i * 37), b = (uint16_t)(60000 - i * 211);
            memcpy(e + 4, &a, 2);
            memcpy(e + 6, &b, 2);
            f = -f;
            memcpy(e + 8, &f, 4);
        }
        std::vector<unsigned char> s = Attributes(d, count, stride, 3, 1);
        // Coverage: the first block's control bytes and the channels.
        int controls[4] = {0, 0, 0, 0};
        for (size_t k = 0; k < stride / 4; ++k)
        {
            for (int j = 0; j < 4; ++j)
            {
                controls[(s[1 + k] >> (2 * j)) & 3] += 1;
            }
        }
        int channels[3] = {0, 0, 0};
        for (size_t k = 0; k < stride / 4; ++k)
        {
            channels[s[s.size() - stride / 4 + k] & 3] += 1;
        }
        fprintf(stderr, "controls %d %d %d %d, channels %d %d %d\n", controls[0], controls[1],
                controls[2], controls[3], channels[0], channels[1], channels[2]);
        if (!controls[0] || !controls[1] || !controls[2] || !controls[3] || !channels[0] ||
            !channels[1] || !channels[2])
        {
            fprintf(stderr, "a mode not covered\n");
            return 1;
        }
        Stream("AttributesV1", s, d, count, stride, 0, true);
    }
    // Triangles and indices at 2 and 4 bytes: a strip-like mesh with some
    // far and repeated indices.
    for (int size = 2; size <= 4; size += 2)
    {
        size_t count = 48 * 3;
        std::vector<unsigned int> idx(count);
        for (size_t t = 0; t < count / 3; ++t)
        {
            unsigned int base = (unsigned int)(t / 2);
            unsigned int far = Next() % 9 == 0 ? 70000u + Next() % 50 : base + 2;
            idx[3 * t + 0] = base;
            idx[3 * t + 1] = base + 1 + (t & 1);
            idx[3 * t + 2] = t % 7 == 0 ? far : base + 2 - (t & 1);
        }
        if (size == 2)
        {
            for (auto& v : idx)
            {
                v &= 0xffff;
            }
        }
        std::vector<unsigned char> tri(meshopt_encodeIndexBufferBound(count, 80000));
        tri.resize(meshopt_encodeIndexBuffer(tri.data(), tri.size(), idx.data(), count));
        std::vector<unsigned char> seq(meshopt_encodeIndexSequenceBound(count, 80000));
        seq.resize(meshopt_encodeIndexSequence(seq.data(), seq.size(), idx.data(), count));
        std::vector<unsigned char> out(count * size);
        for (size_t i = 0; i < count; ++i)
        {
            memcpy(&out[i * size], &idx[i], size);
        }
        // The encoder may rotate a triangle's indices (keeping its
        // winding): the expected output is meshoptimizer's decoding.
        std::vector<unsigned char> rotated(count * size);
        if (meshopt_decodeIndexBuffer(rotated.data(), count, size, tri.data(), tri.size()) != 0)
        {
            fprintf(stderr, "triangles undecodable\n");
            return 1;
        }
        Stream(size == 2 ? "Triangles16" : "Triangles32", tri, rotated, count, size, 1, false);
        Stream(size == 2 ? "Indices16" : "Indices32", seq, out, count, size, 2, false);
    }
    printf("\n");
    // Filters: inputs and meshoptimizer's outputs.
    struct Filter
    {
        const char* name;
        int filter;
        size_t stride;
        int bits;
    };
    const Filter filters[7] = {{"Octahedral8", 1, 4, 8},   {"Octahedral16", 1, 8, 12},
                               {"Quaternion", 2, 8, 11},   {"Exponential", 3, 12, 15},
                               {"Color8", 4, 4, 8},        {"Color16", 4, 8, 13},
                               {"Quaternion16", 2, 8, 16}};
    for (const Filter& f : filters)
    {
        size_t count = 24;
        std::vector<float> v(count * 4);
        for (size_t i = 0; i < count; ++i)
        {
            float* p = &v[i * 4];
            for (int k = 0; k < 4; ++k)
            {
                p[k] = (float)(int)(Next() % 2001 - 1000) / 1000.0f;
            }
            if (f.filter <= 2)
            {
                float l = sqrtf(p[0] * p[0] + p[1] * p[1] + p[2] * p[2] +
                                (f.filter == 2 ? p[3] * p[3] : 0.0f));
                for (int k = 0; k < (f.filter == 2 ? 4 : 3); ++k)
                {
                    p[k] = l > 0 ? p[k] / l : (k == 0 ? 1.0f : 0.0f);
                }
            }
            if (f.filter == 4)
            {
                for (int k = 0; k < 4; ++k)
                {
                    p[k] = fabsf(p[k]);
                }
            }
            if (f.filter == 3)
            {
                for (int k = 0; k < 4; ++k)
                {
                    p[k] = ldexpf(p[k], (int)(Next() % 40) - 20);
                }
            }
        }
        size_t elements = f.filter == 3 ? count * (f.stride / 4) : count;
        std::vector<unsigned char> in(count * f.stride), out;
        switch (f.filter)
        {
        case 1:
            meshopt_encodeFilterOct(in.data(), count, f.stride, f.bits, v.data());
            break;
        case 2:
            meshopt_encodeFilterQuat(in.data(), count, f.stride, f.bits, v.data());
            break;
        case 3:
            meshopt_encodeFilterExp(in.data(), elements, 4, f.bits, v.data(),
                                    meshopt_EncodeExpSeparate);
            break;
        default:
            meshopt_encodeFilterColor(in.data(), count, f.stride, f.bits, v.data());
            break;
        }
        out = in;
        switch (f.filter)
        {
        case 1:
            meshopt_decodeFilterOct(out.data(), count, f.stride);
            break;
        case 2:
            meshopt_decodeFilterQuat(out.data(), count, f.stride);
            break;
        case 3:
            meshopt_decodeFilterExp(out.data(), elements, 4);
            break;
        default:
            meshopt_decodeFilterColor(out.data(), count, f.stride);
            break;
        }
        std::string n = std::string("k") + f.name;
        Bytes((n + "In").c_str(), in.data(), in.size());
        Bytes((n + "Out").c_str(), out.data(), out.size());
    }
    printf("\n// The streams: stream, decoded data, count, stride, mode, version 1.\n"
           "typedef struct MeshoptFixture\n{\n    const uint8_t* stream;\n    size_t size;\n"
           "    const uint8_t* out;\n    uint32_t count;\n    uint32_t stride;\n    int mode;\n"
           "    int v1;\n} MeshoptFixture;\n\nstatic const MeshoptFixture kMeshoptFixtures[] = {\n");
    for (const Case& c : s_cases)
    {
        printf("    {k%s, %zu, k%sOut, %zu, %zu, %d, %d},\n", c.name.c_str(), c.size, c.name.c_str(),
               c.count, c.stride, c.mode, c.v1 ? 1 : 0);
    }
    printf("};\n\n// The filters: input, meshoptimizer's output, count, stride, filter.\n"
           "typedef struct MeshoptFilterFixture\n{\n    const uint8_t* in;\n    const uint8_t* out;\n"
           "    uint32_t count;\n    uint32_t stride;\n    int filter;\n} MeshoptFilterFixture;\n\n"
           "static const MeshoptFilterFixture kMeshoptFilterFixtures[] = {\n");
    for (const Filter& f : filters)
    {
        printf("    {k%sIn, k%sOut, 24, %zu, %d},\n", f.name, f.name, f.stride, f.filter);
    }
    printf("};\n\n#endif // MAUL_ANIM_TEST_GLTF_MESHOPT_FIXTURES_H\n");
    return 0;
}
