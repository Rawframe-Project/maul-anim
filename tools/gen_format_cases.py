# The binary32 writer's oracle: values and the text ECMAScript's Number
# to String writes for them, but with binary32's shortest digits (the
# fewest that round back to the value, the nearest of those, the even one
# of a tie), from exact rationals; written as a C table for test_json.c.
# Deterministic: a fixed seed.
#
# usage: gen_format_cases.py > test/json_format_cases.h
#        gen_format_cases.py --check   (the header matches)

import os
import random
import sys
from fractions import Fraction

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_number_cases import round_to  # noqa: E402


def value_of(bits):
    exponent = (bits >> 23) & 0xFF
    fraction = bits & 0x7FFFFF
    if exponent == 0:
        return Fraction(fraction) * Fraction(2) ** -149
    return Fraction(fraction | 0x800000) * Fraction(2) ** (exponent - 150)


def shortest(bits):
    """Digits s and n with s times 10^(n - len(s)) the value's text."""
    v = value_of(bits)
    # n with 10^(n-1) <= v < 10^n.
    n = len(str(v.numerator)) - len(str(v.denominator))
    while Fraction(10) ** n <= v:
        n += 1
    while Fraction(10) ** (n - 1) > v:
        n -= 1
    for k in range(1, 10):
        unit = Fraction(10) ** (n - k)
        low = (v / unit).numerator // (v / unit).denominator
        found = [s for s in (low, low + 1) if round_to(s * unit, 32) == bits]
        if not found:
            continue
        found.sort(key=lambda s: (abs(s * unit - v), s % 2))
        s = found[0]
        digits = str(s)
        # A carry to a new digit: one more power, a zero dropped.
        return digits.rstrip("0") or "0", n + len(digits) - k
    raise AssertionError("nine digits always suffice")


def layout(s, n):
    """ES5.1 9.8.1 steps 6 to 10 for s times 10^(n - len(s))."""
    k = len(s)
    if k <= n <= 21:
        return s + "0" * (n - k)
    if 0 < n <= 21:
        return s[:n] + "." + s[n:]
    if -6 < n <= 0:
        return "0." + "0" * -n + s
    x = n - 1
    exp = ("+" if x >= 0 else "-") + str(abs(x))
    return s[0] + ("." + s[1:] if k > 1 else "") + "e" + exp


def text_of(bits):
    sign = "-" if bits >> 31 else ""
    magnitude = bits & 0x7FFFFFFF
    if magnitude == 0:
        return sign + "0"
    return sign + layout(*shortest(magnitude))


def cases():
    rnd = random.Random(0x666D7432)
    out = [0x00000000, 0x80000000, 0x3F800000, 0xBF800000, 0x3DCCCCCD, 0x3E4CCCCD,
           0x3E99999A, 0x00000001, 0x80000001, 0x00000002, 0x007FFFFF, 0x00800000,
           0x7F7FFFFF, 0xFF7FFFFF, 0x4B800000, 0x4B800001, 0x4CEB79A3, 0x501502F9,
           0x60AD78EC, 0x60AD78EB, 0x358637BD, 0x3727C5AC, 0x33D6BF95, 0x49742400,
           0x5F5E1000, 0x4E6E6B28, 0x3F7FFFFF, 0x3F800001, 0x40490FDB, 0x7E967699]
    # Powers of two and of ten, and their neighbours.
    for e in range(-149, 128):
        b = round_to(Fraction(2) ** e, 32)
        out += [b, b + 1, b - 1] if b > 1 else [b, b + 1]
    for e in range(-45, 39):
        b = round_to(Fraction(10) ** e, 32)
        if b is not None and b != 0:
            out += [b, b + 1, b - 1]
    for _ in range(3000):
        out.append(rnd.getrandbits(32) & 0xFF7FFFFF if rnd.random() < 0.5
                   else rnd.getrandbits(32) & 0x807FFFFF | rnd.randrange(1, 255) << 23)
    seen = set()
    rows = []
    for b in out:
        if (b >> 23) & 0xFF == 0xFF or b in seen:
            continue
        seen.add(b)
        rows.append((b, text_of(b)))
    return rows


def render():
    lines = ["// SPDX-License-Identifier: MIT",
             "// Copyright (c) 2026 Sirac Ozmen",
             "//",
             "// Generated by tools/gen_format_cases.py: binary32 values and the text",
             "// ECMAScript's layout gives their shortest digits, from exact",
             "// rationals. Do not edit.",
             "",
             "typedef struct FormatCase",
             "{",
             "    uint32_t bits;",
             "    const char* text;",
             "} FormatCase;",
             "",
             "// clang-format off",
             "static const FormatCase kFormatCases[] = {"]
    for b, text in cases():
        lines.append(f'    {{0x{b:08x}u, "{text}"}},')
    lines += ["};", "// clang-format on"]
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if len(sys.argv) > 1 and sys.argv[1] == "--check":
        path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                            "test", "json_format_cases.h")
        if open(path, encoding="utf-8").read() != text:
            print("test/json_format_cases.h differs from tools/gen_format_cases.py")
            sys.exit(1)
        return
    sys.stdout.write(text)


if __name__ == "__main__":
    main()
