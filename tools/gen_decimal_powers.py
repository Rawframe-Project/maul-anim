# Writes src/generated/decimal_powers.h, the powers of five the decimal
# reader's fast path multiplies by (src/decimal.c, Eisel and Lemire's
# method, Lemire 2021): 5^q for q from -342 to 308, each normalized so
# its top bit is the 128th and truncated to 128 bits; below q = 0 the
# reciprocal 2^b / 5^-q, plus one, truncated the same way. Exact integer
# arithmetic; the same words as fast_float's power_of_five_128.
#
# usage: gen_decimal_powers.py [--check]
#   --check  fail when the file differs from what would be written

import os
import sys

SMALLEST = -342
LARGEST = 308
PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "generated",
                    "decimal_powers.h")


def power(q):
    """5^q in 128 bits, as the method reads it."""
    if q >= 0:
        p = 5 ** q
        while p < (1 << 127):
            p *= 2
        while p >= (1 << 128):
            p //= 2
        return p
    five = 5 ** -q
    z = five.bit_length()
    # A quotient of 128 bits or more, then truncated: 2^(z + 127) is
    # enough while 5^-q fits in 64 bits.
    b = z + 127 if q >= -27 else 2 * z + 2 * 64
    p = (1 << b) // five + 1
    while p >= (1 << 128):
        p //= 2
    return p


def text():
    lines = [
        "// SPDX-License-Identifier: MIT",
        "// Copyright (c) 2026 Sirac Ozmen",
        "//",
        "// Generated by tools/gen_decimal_powers.py; do not edit. 5^q for q from",
        "// %d to %d in 128 bits, the high word then the low, for the decimal" % (SMALLEST, LARGEST),
        "// reader's fast path (src/decimal.c).",
        "// clang-format off",
        "",
        "#ifndef MANI_DECIMAL_POWERS_H",
        "#define MANI_DECIMAL_POWERS_H",
        "",
        "#include <stdint.h>",
        "",
        "#define MANI_DECIMAL_SMALLEST_POWER (%d)" % SMALLEST,
        "#define MANI_DECIMAL_LARGEST_POWER %d" % LARGEST,
        "",
        "static const uint64_t kPowersOfFive[%d] = {" % (2 * (LARGEST - SMALLEST + 1)),
    ]
    for q in range(SMALLEST, LARGEST + 1):
        p = power(q)
        lines.append("    0x%016xu, 0x%016xu, // 5^%d" % (p >> 64, p & ((1 << 64) - 1), q))
    lines += ["};", "", "#endif // MANI_DECIMAL_POWERS_H", ""]
    return "\n".join(lines)


def main():
    check = len(sys.argv) > 1 and sys.argv[1] == "--check"
    want = text()
    if check:
        current = ""
        if os.path.exists(PATH):
            with open(PATH, encoding="utf-8") as f:
                current = f.read()
        if current != want:
            print("src/generated/decimal_powers.h is stale: run tools/gen_decimal_powers.py")
            return 1
        print("decimal powers: current")
        return 0
    with open(PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write(want)
    print("wrote " + os.path.normpath(PATH))
    return 0


if __name__ == "__main__":
    sys.exit(main())
